from datetime import date as date_type
from typing import List, Optional

from pydantic import BaseModel, ConfigDict, Field


class MovieDetailResponseSchema(BaseModel):
    id: int = Field(
        ...,
        title="Movie ID",
        description="Unique identifier of the movie in the database.",
    )
    name: str = Field(
        ...,
        title="Name",
        description="Title of the movie.",
    )
    date: date_type = Field(
        ...,
        title="Release Date",
        description="Date the movie was released.",
    )
    score: float = Field(
        ...,
        title="Score",
        description="Movie rating, a float between 0 and 100.",
    )
    genre: Optional[str] = Field(
        default=None,
        title="Genre",
        description="Comma-separated list of genres associated with the movie.",
    )
    overview: Optional[str] = Field(
        default=None,
        title="Overview",
        description="Short description or synopsis of the movie.",
    )
    crew: Optional[str] = Field(
        default=None,
        title="Crew",
        description="List of cast and crew members involved in the movie.",
    )
    orig_title: Optional[str] = Field(
        default=None,
        title="Original Title",
        description="Original title of the movie, if different from the localized name.",
    )
    status: Optional[str] = Field(
        default=None,
        title="Status",
        description="Release status of the movie, e.g. 'Released' or 'Post-production'.",
    )
    orig_lang: Optional[str] = Field(
        default=None,
        title="Original Language",
        description="Original language the movie was produced in.",
    )
    budget: Optional[float] = Field(
        default=None,
        title="Budget",
        description="Budget spent on producing the movie, in USD.",
    )
    revenue: Optional[float] = Field(
        default=None,
        title="Revenue",
        description="Revenue generated by the movie, in USD.",
    )
    country: Optional[str] = Field(
        default=None,
        title="Country",
        description="Country where the movie was produced.",
    )

    model_config = ConfigDict(from_attributes=True)


class MovieListResponseSchema(BaseModel):
    movies: List[MovieDetailResponseSchema] = Field(
        ...,
        title="Movies",
        description="List of movies for the current page.",
    )
    prev_page: Optional[str] = Field(
        default=None,
        title="Previous Page",
        description="URL of the previous page of results, if it exists.",
    )
    next_page: Optional[str] = Field(
        default=None,
        title="Next Page",
        description="URL of the next page of results, if it exists.",
    )
    total_pages: int = Field(
        ...,
        title="Total Pages",
        description="Total number of pages available given the current per_page value.",
    )
    total_items: int = Field(
        ...,
        title="Total Items",
        description="Total number of movies matching the query.",
    )
